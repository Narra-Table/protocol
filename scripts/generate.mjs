// Generates TypeScript declarations from contract/. Run `pnpm generate`; `pnpm check` fails on drift.
import { mkdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { isDeepStrictEqual } from 'node:util';
import openapiTS, { astToString } from 'openapi-typescript';
import { contractDir, listFiles, readJSON, root, verifyBundle } from './contract.mjs';

const typeName = (ref) => ref.slice(ref.lastIndexOf('/') + 1);
const ident = /^[A-Za-z_$][\w$]*$/;
const key = (k) => (ident.test(k) ? k : JSON.stringify(k));

// Standalone value schemas (schemas/<Name>.json with a root allOf) such as Audience.
function standalone() {
  const out = {};
  for (const file of listFiles(join(contractDir, 'schemas'))) {
    const doc = readJSON(join(contractDir, 'schemas'), file);
    if (doc.allOf) out[file.replace(/\.json$/, '')] = doc.allOf[0];
  }
  return out;
}

// Realtime and plugin documents share one registry of $defs; expose it as OpenAPI components.
function wireDocument(realtime, plugin) {
  for (const [name, schema] of Object.entries(plugin.$defs)) {
    if (realtime.$defs[name] && !isDeepStrictEqual(realtime.$defs[name], schema)) {
      throw new Error(`realtime.json and plugin.json disagree on ${name}`);
    }
  }
  const schemas = JSON.parse(
    JSON.stringify({ ...realtime.$defs, ...plugin.$defs, ...standalone() }).replaceAll(
      '"#/$defs/',
      '"#/components/schemas/',
    ),
  );
  return { openapi: '3.1.0', info: { title: 'NarraTable wire', version: '0' }, paths: {}, components: { schemas } };
}

// One name must mean one shape across HTTP and wire definitions.
function assertSameShapes(http, wire) {
  const norm = (s) => JSON.stringify(s);
  for (const [name, schema] of Object.entries(wire.components.schemas)) {
    const other = http.components.schemas[name];
    if (other && norm(other) !== norm(schema)) throw new Error(`HTTP and wire disagree on ${name}`);
  }
}

function aliases(http, wire, realtime, plugin) {
  const lines = [];
  const httpNames = Object.keys(http.components.schemas).sort();
  const wireNames = Object.keys(wire.components.schemas).filter((n) => !httpNames.includes(n)).sort();
  lines.push(`import type { components as HttpComponents, operations, paths } from './http';`);
  lines.push(`import type { components as WireComponents } from './wire';`);
  lines.push('', 'export type { operations, paths };');
  lines.push(`export type Schemas = HttpComponents['schemas'];`);
  lines.push(`export type WireSchemas = WireComponents['schemas'];`, '');
  for (const n of httpNames) lines.push(`export type ${n} = Schemas['${n}'];`);
  for (const n of wireNames) lines.push(`export type ${n} = WireSchemas['${n}'];`);

  const frameMap = (name, frames) => {
    lines.push('', `export interface ${name} {`);
    for (const [type, schema] of Object.entries(frames).sort()) lines.push(`  ${key(type)}: ${typeName(schema.$ref)};`);
    lines.push('}');
  };
  frameMap('ClientFrames', realtime.client);
  frameMap('ServerFrames', realtime.server);
  lines.push('export type ClientFrame = ClientFrames[keyof ClientFrames];');
  lines.push('export type ServerFrame = ServerFrames[keyof ServerFrames];');
  lines.push('export type ClientFrameType = keyof ClientFrames;');
  lines.push('export type ServerFrameType = keyof ServerFrames;');

  const tsOf = (s) => (s.$ref ? typeName(s.$ref) : s.type === 'integer' ? 'number' : s.type);
  lines.push('', 'export interface CpiMethods {');
  for (const [name, m] of Object.entries(plugin.cpi).sort()) {
    lines.push(`  ${key(name)}: { capability: ${JSON.stringify(m.capability)}; input: ${tsOf(m.input)}; output: ${tsOf(m.output)} };`);
  }
  lines.push('}');
  lines.push(`export type BridgeMethod = ${plugin.bridgeMethods.map((m) => JSON.stringify(m)).join(' | ')};`);
  lines.push('export interface BridgeInputs {');
  for (const [name, s] of Object.entries(plugin.bridgeInputs).sort()) lines.push(`  ${key(name)}: ${typeName(s.$ref)};`);
  lines.push('}');
  return lines.join('\n') + '\n';
}

export async function generate() {
  const source = verifyBundle(contractDir);
  const http = readJSON(contractDir, 'openapi.json');
  const realtime = readJSON(contractDir, 'realtime.json');
  const plugin = readJSON(contractDir, 'plugin.json');
  const wire = wireDocument(realtime, plugin);
  assertSameShapes(http, wire);
  const banner =
    `// Generated by scripts/generate.mjs from contract/. Do not edit.\n` +
    `// backendCommit ${source.backendCommit} contractHash ${source.contractHash}\n\n`;
  const options = { alphabetize: true, rootTypes: false };
  return {
    'generated/http.d.ts': banner + astToString(await openapiTS(http, options)),
    'generated/wire.d.ts': banner + astToString(await openapiTS(wire, options)),
    'generated/index.d.ts': banner + aliases(http, wire, realtime, plugin),
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const files = await generate();
  mkdirSync(join(root, 'generated'), { recursive: true });
  for (const [name, content] of Object.entries(files)) writeFileSync(join(root, name), content);
  console.log(`generated ${Object.keys(files).join(', ')}`);
}
